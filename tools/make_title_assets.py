"""Create original tape/drone audio and portable Latin font subsets for the title."""
from pathlib import Path
import array
import math
import random
import subprocess
import tempfile
import wave
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
RATE = 44100


def audio(path, duration, sample):
    data = array.array("h")
    randomizer = random.Random(240)
    low = 0.0
    for i in range(round(duration * RATE)):
        t = i / RATE
        noise = randomizer.uniform(-1, 1)
        low += (noise - low) * .025
        left, right = sample(t, noise, low)
        data.extend(round(max(-.8, min(.8, value)) * 32767) for value in [left, right])
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(2)
        stream.setsampwidth(2)
        stream.setframerate(RATE)
        stream.writeframes(data.tobytes())


def ambient(t, noise, low):
    envelope = min(1, t / .2, (20 - t) / .2)
    breath = .8 + .2 * math.sin(math.tau * t / 20)
    drone = .16 * math.sin(math.tau * 55 * t) + .10 * math.sin(math.tau * 55.2 * t)
    drone += .065 * math.sin(math.tau * 82.4 * t) + .035 * math.sin(math.tau * 110 * t)
    air = low * .2 + noise * .004
    metallic = 0
    for onset in [4.1, 12.6]:
        age = t - onset
        if age >= 0:
            metallic += .025 * math.exp(-age * 1.7) * math.sin(math.tau * 659.25 * age)
    base = (drone * breath + air + metallic) * envelope
    return base, base * .93 + .018 * math.sin(math.tau * 55.1 * t) * envelope


def tape(t, noise, low):
    value = 0
    for onset in [.04, .42, 4.1, 8.2]:
        age = t - onset
        if 0 <= age < .3:
            value += (.24 * noise + .12 * math.sin(math.tau * 110 * age)) * math.exp(-age * 35)
    if .45 < t < 1.1:
        value += .05 * noise * math.sin(math.pi * (t - .45) / .65)
    if 1.3 < t < 4.4:
        value += .023 * math.sin(math.tau * (155 - t * 9) * t) * math.sin(math.pi * (t - 1.3) / 3.1)
    age = t - 4.2
    if age >= 0:
        value += .18 * math.sin(math.tau * 43.65 * age) * math.exp(-age * 1.4)
    return value, value * .94


def main():
    output = ROOT / "assets/audio/title"
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="thelastsale-title-") as folder:
        for name, duration, sample in [("title_drone", 20, ambient), ("intro_tape", 9, tape)]:
            source = Path(folder) / (name + ".wav")
            audio(source, duration, sample)
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(source),
                            "-c:a", "libvorbis", "-q:a", "2", str(output / (name + ".ogg"))], check=True)
    audio(output / "select.wav", .07,
          lambda t, noise, low: ((.18 * math.sin(math.tau * 900 * t) + .05 * noise) * math.exp(-t * 100),) * 2)
    fonts = ROOT / "assets/fonts/title"
    fonts.mkdir(parents=True, exist_ok=True)
    characters = set(range(0x20, 0x250)) | {0x2014, 0x2022, 0x2026, 0x2192, 0x25B6}
    for source, name in [("DejaVuSerifCondensed-Bold.ttf", "TitleSerif.ttf"),
                         ("DejaVuSansMono.ttf", "TitleMono.ttf")]:
        options = subset.Options()
        font = subset.load_font("/usr/share/fonts/truetype/dejavu/" + source, options)
        reducer = subset.Subsetter(options=options)
        reducer.populate(unicodes=characters)
        reducer.subset(font)
        subset.save_font(font, str(fonts / name), options)
    notice = Path("/usr/share/doc/fonts-dejavu/copyright").read_text().split("Files: debian/*")[0]
    (fonts / "LICENSE.txt").write_text(notice)
    (output / "README.txt").write_text("Original synthesized audio for A Última Venda, generated by tools/make_title_assets.py.\nNo recordings or music from other games are used.\n")
    for path in sorted([*output.glob("*"), *fonts.glob("*")]):
        print(path.relative_to(ROOT), path.stat().st_size)


if __name__ == "__main__":
    main()
